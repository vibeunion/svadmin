import { spawnSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import postcss from 'postcss';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(import.meta.url);
const cli = join(dirname(require.resolve('@pandacss/dev/package.json')), 'bin.js');
const generated = resolve(root, '../../node_modules/.cache/svadmin-surface-panda');
const stylesheet = join(generated, 'editor.css');
const check = process.argv.includes('--check');
mkdirSync(generated, { recursive: true });
for (const args of [['codegen'], ['cssgen', '--outfile', stylesheet]]) {
  const result = spawnSync(process.execPath, [cli, ...args, '--config', 'panda.config.ts'], { cwd: root, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`Panda ${args[0]} failed`);
}
const recipes = await import(pathToFileURL(join(generated, 'recipes/index.mjs')).href);
const editorClasses = Object.fromEntries(['compact', 'comfortable'].map((density) => [density, recipes.surfaceEditor({ density })]));
const editorButtonClasses = Object.fromEntries(['secondary', 'primary'].map((variant) => [variant, recipes.surfaceEditorButton({ variant })]));
const rootCss = postcss.parse(readFileSync(stylesheet, 'utf8'));
// preset-base 的变换/滤镜变量初始化是全局选择器，本组件不用这些能力；明确去掉该层。
rootCss.walkAtRules('layer', (rule) => { if (rule.params === 'sv-surface.base') rule.remove(); });
rootCss.walkRules((rule) => {
  if (!rule.selector.startsWith('.svsurface-') && rule.selector !== '.svadmin-surface-editor') {
    throw new Error(`Unscoped selector in Surface CSS: ${rule.selector}`);
  }
});
const css = rootCss.toString();
if (Buffer.byteLength(css) > 32_768 || /@(?:import|tailwind|theme|apply)\b/u.test(css)) {
  throw new Error('Surface styles must be bounded, standalone compiled CSS');
}
for (const value of [...Object.values(editorClasses), ...Object.values(editorButtonClasses)]) {
  for (const name of value.split(/\s+/u)) {
    if (!css.includes(`.${name}`)) throw new Error(`Missing compiled Panda variant: ${name}`);
  }
}
const files = {
  'src/styles/editor.css': css,
  'src/styles/editor.generated.ts': '// Generated by scripts/build-editor-styles.mjs; do not edit.\n' +
    `export const editorClasses = ${JSON.stringify(editorClasses, null, 2)} as const;\n` +
    `export const editorButtonClasses = ${JSON.stringify(editorButtonClasses, null, 2)} as const;\n`,
};
for (const [relative, content] of Object.entries(files)) {
  const target = join(root, relative);
  if (check) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Generated styles are stale: ${relative}`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}
console.info(`Surface editor: ${Buffer.byteLength(css)} CSS bytes; all four finite variants covered`);
