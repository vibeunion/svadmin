type TranslationContext = Pick<ReturnType<typeof useTranslation>, 'locale' | 't'>;

/** 优先使用宿主翻译；回退词条兼容尚未包含新键的 Core。 */
export function filterText(i18n: TranslationContext, key: FilterMessageKey): string {
  const translated = i18n.t(key);
  return translated !== key ? translated : (i18n.locale.startsWith('zh') ? chinese : english)[key];
}

export function filterOperatorText(i18n: TranslationContext, operator: CrudOperator): string {
  return filterText(i18n, `filter.${operator}`);
}
